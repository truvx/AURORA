package dev.aurora.player.domain.discovery

import dev.aurora.player.domain.library.ListeningEventKind
import dev.aurora.player.domain.library.ListeningHistoryRecord
import dev.aurora.player.domain.models.MediaItem
import kotlin.math.pow

/** A track published recently by an artist the listener plays. */
data class Release(
    val item: MediaItem,
    val artist: String,
    val publishedAtMs: Long
)

/** One thing that says something about how much the listener likes an artist. */
data class ArtistSignal(
    val artist: String,
    val kind: SignalKind,
    val timestampMs: Long
)

enum class SignalKind(val weight: Double) {
    /** Listened to the end: the strongest behavioural signal. */
    COMPLETE(3.0),
    PLAY(1.0),
    /** Skipped: counts against, so a disliked artist sinks rather than merely not rising. */
    SKIP(-1.0),
    /** An explicit choice, which outweighs any single listen. */
    FAVORITE(5.0)
}

/**
 * Ranks the artists a listener cares about, on-device, from their own history.
 *
 * Recent behaviour counts for more than old behaviour - taste moves - so each signal decays
 * with a half-life. Names are grouped case- and suffix-insensitively, because the same
 * artist arrives as "Keshi" from a file tag and "keshi - Topic" from YouTube.
 */
object ArtistAffinity {

    const val HALF_LIFE_MS = 30L * 24 * 60 * 60 * 1000

    /** Tags that mean "no artist", which must never be ranked as one. */
    private val PLACEHOLDERS = setOf("unknown artist", "unknown", "various artists", "<unknown>")

    fun topArtists(signals: List<ArtistSignal>, nowMs: Long, limit: Int = 6): List<String> {
        val scores = mutableMapOf<String, Double>()
        val spellings = mutableMapOf<String, MutableMap<String, Int>>()

        for (signal in signals) {
            val display = displayName(signal.artist) ?: continue
            val key = display.lowercase()
            val age = (nowMs - signal.timestampMs).coerceAtLeast(0)
            val decay = 0.5.pow(age.toDouble() / HALF_LIFE_MS)
            scores[key] = (scores[key] ?: 0.0) + signal.kind.weight * decay
            spellings.getOrPut(key) { mutableMapOf() }.merge(display, 1, Int::plus)
        }

        return scores.entries
            .filter { it.value > 0 }
            .sortedWith(compareByDescending<Map.Entry<String, Double>> { it.value }.thenBy { it.key })
            .take(limit)
            // Shown the way it was most often written.
            .map { entry -> spellings.getValue(entry.key).maxBy { it.value }.key }
    }

    /**
     * The artist as a person would write it, or null when the value names no one.
     *
     * Strips YouTube's channel decorations - "Artist - Topic" is YouTube Music's auto
     * channel, "ArtistVEVO" a label channel - so they group with the plain name.
     */
    fun displayName(raw: String?): String? {
        val collapsed = raw?.trim()?.replace(Regex("\\s+"), " ") ?: return null
        val stripped = collapsed
            .removeSuffixIgnoreCase(" - Topic")
            .removeSuffixIgnoreCase("VEVO")
            .trim()
        if (stripped.isEmpty() || stripped.lowercase() in PLACEHOLDERS) return null
        return stripped
    }

    private fun String.removeSuffixIgnoreCase(suffix: String): String =
        if (endsWith(suffix, ignoreCase = true)) dropLast(suffix.length) else this
}

/**
 * Picks an artist's YouTube channel from search results - or declines to.
 *
 * Only exact name matches count. "Artist - Topic" is preferred: it is the channel YouTube
 * Music generates from official releases, so its uploads are the artist's actual records.
 * A near match is refused rather than guessed, because a wrong channel would fill Latest
 * Releases with someone else's music and present it as the listener's artist.
 */
object ChannelMatcher {
    data class Candidate(val channelId: String, val title: String)

    fun pick(artist: String, candidates: List<Candidate>): String? {
        val wanted = normalize(artist)
        candidates.firstOrNull { normalize(it.title) == "$wanted - topic" }?.let { return it.channelId }
        return candidates.firstOrNull { normalize(it.title) == wanted }?.channelId
    }

    private fun normalize(text: String) = text.trim().replace(Regex("\\s+"), " ").lowercase()
}

/** A mood-led playlist, generated by searching when opened. */
data class Mix(
    val id: String,
    val title: String,
    val subtitle: String,
    val query: String,
    val mood: MixMood
)

enum class MixMood(val label: String, val keywords: String, val description: String) {
    CHILL("Chill Mix", "chill relaxing", "Easy listening"),
    FOCUS("Focus Mix", "focus instrumental", "Deep work"),
    WORKOUT("Workout Mix", "high energy workout", "High energy"),
    LATE_NIGHT("Late Night", "late night mellow", "For your nights"),
    DISCOVER("Indie Discoveries", "indie new artists", "New artists"),
    FEEL_GOOD("Feel Good", "upbeat feel good", "Mood lift")
}

/**
 * The "Recommended for You" row.
 *
 * Each mix is a search seeded with the listener's own top artists, which is what makes it
 * theirs. With no history yet the mixes still exist, described by mood rather than claiming
 * to be personal - "Made for you" is only said when it is true.
 */
object MixCatalog {
    fun mixesFor(topArtists: List<String>): List<Mix> {
        val seeds = topArtists.take(2)
        return MixMood.entries.map { mood ->
            val query = if (seeds.isEmpty()) {
                "${mood.keywords} music"
            } else {
                "${mood.keywords} songs like ${seeds.joinToString(" ")}"
            }
            Mix(
                id = mood.name.lowercase(),
                title = mood.label,
                subtitle = if (seeds.isEmpty()) mood.description else "Made for you",
                query = query,
                mood = mood
            )
        }
    }
}

/**
 * What an artist's page is made of, decided without a screen.
 *
 * The page shows the artist's own tracks, most-played first. "Top" has to mean something
 * measurable: it is this listener's play count, not a chart position AURORA has no way to
 * know.
 */
object ArtistPage {

    /**
     * The artist's tracks from a library.
     *
     * Matched on the written name because that is the only identity shared across
     * providers - a local file and a YouTube video have unrelated ids but the same artist.
     * Case and surrounding space vary between taggers and are ignored.
     */
    fun tracksBy(artist: String, library: List<MediaItem>): List<MediaItem> {
        val wanted = artist.trim()
        if (wanted.isEmpty()) return emptyList()
        return library.filter { it.artist?.trim().equals(wanted, ignoreCase = true) }
    }

    /**
     * Most played first, then alphabetical.
     *
     * Alphabetical rather than library order for the tail, so tracks nobody has played yet
     * are in a predictable place instead of whatever order the scan produced.
     */
    fun topSongs(tracks: List<MediaItem>, playsById: Map<String, Int>, limit: Int = 20): List<MediaItem> =
        tracks
            .sortedWith(
                compareByDescending<MediaItem> { playsById[it.id] ?: 0 }
                    .thenBy { it.title.lowercase() }
            )
            .take(limit)

    /**
     * How often each track was actually listened to.
     *
     * Skips do not count. A track started and abandoned eleven times is not this person's
     * favourite, and counting it as one is how "top songs" turns into "songs you keep
     * skipping".
     */
    fun playCounts(history: List<ListeningHistoryRecord>): Map<String, Int> {
        val counts = mutableMapOf<String, Int>()
        for (record in history) {
            if (record.kind == ListeningEventKind.SKIP) continue
            counts[record.mediaId] = (counts[record.mediaId] ?: 0) + 1
        }
        return counts
    }
}
